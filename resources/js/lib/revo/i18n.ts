type Key = keyof (typeof messages)['en'];

export const locale = ref<Locale>('en');

export const direction = computed(() => (locale.value === 'ar' ? 'rtl' : 'ltr'));

export function setLocale(value: string | undefined): void {
    locale.value = value === 'ar' ? 'ar' : 'en';
}

export function t(key: Key | (string & {}), params: Record<string, string | number> = {}): string {
    const table = messages[locale.value] as Record<string, string>;
    const fallback = messages.en as Record<string, string>;
    const text = table[key] ?? fallback[key] ?? key;

    return Object.entries(params).reduce((result, [name, value]) => result.replace(`{${name}}`, String(value)), text);
}
